const L = require('./lib'); const fs = require('fs');
const step = async (name, fn) => { try { await fn(); } catch (e) { console.error('FAIL', name, e.message.split('\n')[0]); throw e; } };
async function choisir(page, libelle, option) { await page.getByLabel(libelle, { exact: true }).click(); await page.getByRole('option', { name: option }).click(); }
(async () => {
  await L.start();
  const g = await L.login('gestionnaire');
  await L.shot(g, 'c00-dashboard-gestionnaire');
  await g.goto(L.BASE + '/membres'); await L.shot(g, 'c01-liste-membres');
  let fiche;
  await step('wizard', async () => {
    await g.getByRole('link', { name: 'Nouvelle adhésion' }).first().click();
    await g.getByRole('heading', { name: 'Nouvelle adhésion' }).waitFor();
    await L.shot(g, 'c02-wizard-vide');
    await g.getByLabel('Nom', { exact: true }).fill('Mwangaza');
    await g.getByLabel('Postnom').fill('Lwaboshi');
    await g.getByLabel('Prénom').fill('David');
    await choisir(g, 'Sexe', 'Masculin');
    await g.getByLabel('Date de naissance').fill('1991-06-12');
    await L.shot(g, 'c03-wizard-identite');
    await g.getByRole('button', { name: 'Suivant' }).click();
    await g.getByLabel('Téléphone', { exact: true }).fill('0997654321');
    await g.getByLabel('Ville ou territoire').fill('Bukavu');
    await L.shot(g, 'c04-wizard-coordonnees');
    await g.getByRole('button', { name: 'Suivant' }).click();
    await g.getByLabel('Numéro').fill('ce-554433');
    await g.getByLabel(/Photo du membre/).setInputFiles('photo-membre.png');
    await g.getByRole('button', { name: 'Remplacer' }).first().waitFor();
    const sig = g.getByLabel(/[Ss]ignature/);
    if (await sig.count()) { await sig.first().setInputFiles('signature.png').catch(e => console.log('sig', e.message.split('\n')[0])); }
    await L.shot(g, 'c05-wizard-piece-photo');
    await L.shot(g, 'c05b-wizard-piece-photo-full', { full: true });
    await g.getByRole('button', { name: 'Suivant' }).click();
    await g.getByRole('button', { name: 'Ajouter un bénéficiaire' }).click();
    await g.getByLabel('Nom complet').fill('Neema Mwangaza');
    await g.getByLabel('Lien').fill('Conjointe');
    await L.shot(g, 'c06-wizard-beneficiaire');
    await g.getByRole('button', { name: 'Suivant' }).click();
    await g.getByText('MWANGAZA LWABOSHI David').first().waitFor();
    await L.shot(g, 'c07-wizard-recap');
    await L.shot(g, 'c07b-wizard-recap-full', { full: true });
    await g.getByRole('button', { name: "Enregistrer l'inscription" }).click();
    await g.waitForURL(/\/membres\/[0-9a-f-]{36}$/);
    fiche = new URL(g.url()).pathname;
    await L.shot(g, 'c08-fiche-en-attente');
    fs.writeFileSync('state.json', JSON.stringify({ fiche }));
  });
  const c = await L.login('caissier');
  await step('adhesion', async () => {
    await c.goto(L.BASE + fiche);
    await c.getByRole('button', { name: "Encaisser l'adhésion" }).click();
    const d = c.getByRole('dialog');
    await d.getByText(/Total à encaisser/).waitFor();
    await L.shot(c, 'c10-encaisser-adhesion');
    const [recu] = await Promise.all([c.context().waitForEvent('page'), d.getByRole('button', { name: 'Encaisser' }).click()]);
    await c.getByText('Adhésion encaissée : le membre est actif.').waitFor();
    await L.shot(c, 'c11-adhesion-ok');
    await recu.setViewportSize({ width: 1536, height: 864 }); await recu.waitForLoadState('networkidle');
    await L.shot(recu, 'c12-recu-adhesion'); await L.shot(recu, 'c12b-recu-adhesion-full', { full: true });
    await recu.close();
    await c.reload(); await L.shot(c, 'c13-fiche-active');
  });
  await step('compte', async () => {
    await g.goto(L.BASE + fiche); await g.reload();
    await L.shot(g, 'c14-fiche-360');
    await g.getByRole('tab', { name: /Comptes/ }).click();
    await g.getByRole('button', { name: 'Ouvrir un compte' }).click();
    await L.shot(g, 'c15-ouvrir-compte');
    await g.getByRole('dialog').getByRole('button', { name: 'Ouvrir' }).click();
    await g.waitForURL(/\/epargne\/[0-9a-f-]{36}$/);
    const compte = new URL(g.url()).pathname;
    await L.shot(g, 'c16-compte-ouvert');
    fs.writeFileSync('state.json', JSON.stringify({ fiche, compte }));
  });
  await step('depot', async () => {
    await c.goto(L.BASE + '/caisse');
    await c.getByRole('button', { name: 'Dépôt' }).click();
    const d = c.getByRole('dialog');
    await d.getByLabel('Compte ou membre').fill('Mwangaza');
    await c.waitForTimeout(800);
    await L.shot(c, 'c20-depot-recherche');
    await d.getByRole('button', { name: /EP-/ }).first().click();
    await d.getByLabel('Montant').fill('750000');
    await c.waitForTimeout(500);
    await L.shot(c, 'c21-depot-saisi');
    const [recu] = await Promise.all([c.context().waitForEvent('page'), d.getByRole('button', { name: 'Encaisser' }).click()]);
    await recu.setViewportSize({ width: 1536, height: 864 }); await recu.waitForLoadState('networkidle');
    await L.shot(recu, 'c22-recu-depot'); await L.shot(recu, 'c22b-recu-depot-full', { full: true });
    await recu.close();
    await c.waitForTimeout(800); await L.shot(c, 'c23-caisse-apres-depot');
  });
  await L.browser.close();
})().catch(e => { console.error(e.message); process.exit(1); });
